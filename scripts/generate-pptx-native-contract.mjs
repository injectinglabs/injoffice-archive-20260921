for (const elementName of ['textElement', 'shapeElement', 'connectorElement', 'pictureElement', 'tableElement', 'chartElement', 'groupElement']) {
  assertedLimits.push([schema.$defs[elementName].properties.passthrough.maxItems, 'maxPassthroughPerObject', `$defs.${elementName}.passthrough.maxItems`])
}
assertedLimits.push(
  [schema.$defs.asset.properties.passthrough.maxItems, 'maxPassthroughPerObject', '$defs.asset.passthrough.maxItems'],
  [schema.$defs.slide.properties.passthrough.maxItems, 'maxPassthroughPerObject', '$defs.slide.passthrough.maxItems'],
)
for (const [actual, limitName, location] of assertedLimits) {
  if (actual !== resourceLimits[limitName]) throw new Error(`${location} must equal x-resource-limits.${limitName}`)
}

async function emit(path, contents, trailingNewline = true) {
  if (trailingNewline && !contents.endsWith('\n')) contents += '\n'
  if (check) {
    let existing = ''
    try { existing = await readFile(path, 'utf8') } catch {}
    if (existing !== contents) {
      throw new Error(`${path} is stale; run npm run generate:pptx-contract`)
    }
    return
  }
  await writeFile(path, contents)
}

await emit(tsPath, ts)
await emit(goPath, go)
const canonicalInput = JSON.parse(await readFile(canonicalInputPath, 'utf8'))
canonicalInput.assets.sort((left, right) => left.id < right.id ? -1 : left.id > right.id ? 1 : 0)
await emit(canonicalGoldenPath, stringifyCanonical(canonicalInput), false)
console.log(`${check ? 'checked' : 'generated'} PPTX native contract ${digest}`)

function stringifyCanonical(value) {
  if (value === null) return 'null'
  if (typeof value === 'string') return JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029')
  if (typeof value === 'boolean' || typeof value === 'number') return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map(stringifyCanonical).join(',')}]`
  const keys = Object.keys(value).sort()
  return `{${keys.map((key) => `${stringifyCanonical(key)}:${stringifyCanonical(value[key])}`).join(',')}}`
}
