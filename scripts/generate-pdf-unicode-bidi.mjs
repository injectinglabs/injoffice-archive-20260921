import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { gunzipSync } from 'node:zlib'
import { resolve } from 'node:path'

// Unicode17 primary data, retained verbatim/compressed under the Unicode license.
// No network access is required to regenerate or validate the runtime tables.
const root = resolve(import.meta.dirname, '..')
const hashes = {
  DerivedBidiClass: '4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4',
  BidiBrackets: 'dadbaf38a0d0246e5b805bf8725cb81b7c621f93d030595635f5ba2c2f179428',
  UnicodeData: '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
  BidiTest: '888bdfc8090652272d1f859cdb00ae659e2dc6c26740be61ef1d03998a687620',
  BidiCharacterTest: 'a3e6e905ab5afbe318a96df5401d0372a04cd73ef139ab5e3cf0ae241c255488',
}
const sources = Object.fromEntries(Object.entries(hashes).map(([name, hash]) => {
  const bytes = gunzipSync(readFileSync(resolve(root, `packages/pdf/testdata/unicode17/${name}.txt.gz`)))
  if (createHash('sha256').update(bytes).digest('hex') !== hash) throw new Error(`Unicode17 ${name} input hash mismatch`)
  return [name, bytes.toString('utf8')]
}))
const classes = Array(0x110000).fill('L')
const aliases = { Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET' }
const applyRange = (range, type) => {
  const [first, last = first] = range.trim().split('..').map(value => Number.parseInt(value, 16))
  if (!Number.isInteger(first) || !Number.isInteger(last) || first < 0 || last < first || last > 0x10ffff) throw new Error('Invalid Unicode bidi range')
  classes.fill(aliases[type.trim()] ?? type.trim(), first, last + 1)
}
// Normative unassigned-codepoint defaults are overridden by explicit entries.
for (const match of sources.DerivedBidiClass.matchAll(/# @missing: ([^;]+); ([^\n]+)/g)) applyRange(match[1], match[2])
for (const line of sources.DerivedBidiClass.split('\n')) {
  const clean = line.split('#')[0].trim()
  if (clean) applyRange(...clean.split(';'))
}
const byClass = new Map()
classes.forEach((type, code) => {
  if (type === 'L') return
  if (!byClass.has(type)) byClass.set(type, [])
  byClass.get(type).push(code)
})
const compressed = {}
for (const [type, codes] of [...byClass].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  const ranges = []
  let last = 0
  for (let index = 0; index < codes.length;) {
    const start = codes[index++]
    let end = start
    while (index < codes.length && codes[index] === end + 1) end = codes[index++]
    ranges.push((start - last).toString(36) + (end > start ? `+${(end - start).toString(36)}` : ''))
    last = end
  }
  compressed[type] = ranges.join(',')
}
const pairs = {}
for (const line of sources.BidiBrackets.split('\n')) {
  const clean = line.split('#')[0].trim()
  if (!clean) continue
  const [code, paired, type] = clean.split(';').map(value => value.trim())
  if (type === 'o') pairs[String.fromCodePoint(Number.parseInt(code, 16))] = String.fromCodePoint(Number.parseInt(paired, 16))
}
const decompositions = new Map()
for (const line of sources.UnicodeData.split('\n')) {
  const fields = line.split(';')
  if (fields[5] && !fields[5].startsWith('<')) decompositions.set(String.fromCodePoint(Number.parseInt(fields[0], 16)), fields[5].split(' ').map(code => String.fromCodePoint(Number.parseInt(code, 16))).join(''))
}
const decompose = character => decompositions.has(character) ? [...decompositions.get(character)].map(decompose).join('') : character
const canonical = {}
for (const char of new Set([...Object.keys(pairs), ...Object.values(pairs)])) {
  const value = decompose(char)
  if (value !== char) canonical[char] = value
}
const text = `// Generated by scripts/generate-pdf-unicode-bidi.mjs; do not edit.\n// Unicode17.0.0, Copyright ©2025 Unicode, Inc. Unicode License V3.\n// Sources: https://www.unicode.org/Public/17.0.0/ucd/ (extracted/DerivedBidiClass).\n// Full input hashes include the official conformance suites.\nexport const UNICODE_VERSION = '17.0.0'\nexport const INPUT_SHA256 = ${JSON.stringify(hashes, null, 2)}\nexport const BIDI_CLASSES = ${JSON.stringify(compressed, null, 2)}\nexport const BRACKET_PAIRS = ${JSON.stringify(pairs, null, 2)}\nexport const CANONICAL_BRACKETS = ${JSON.stringify(canonical, null, 2)}\n`
const path = resolve(root, 'packages/pdf/src/annotate/unicodeBidiVendor/unicode17.generated.js')
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text) throw new Error('Generated PDF Unicode17 bidi tables are stale')
  console.log('PDF Unicode17 data hashes and generated tables match')
} else writeFileSync(path, text)
